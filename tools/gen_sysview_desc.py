#!/usr/bin/env python3
"""
gen_sysview_desc.py - generate SYSVIEW_ThreadX_native.txt from upstream
ThreadX's tx_trace.h.

txsv_adapter.c records every native trace point as SystemView event
(TX_TRACE_<X> + 32) with the trace point's four ULONGs (I1..I4) as
parameters, and names the OS "ThreadX_native" in the system description.
SystemView then decodes the events with SYSVIEW_ThreadX_native.txt. The stock
SYSVIEW_ThreadX.txt describes the SEGGERMicro/threadx fork's own event IDs
and parameters, so with it every native event shows under a wrong name.

    tools/gen_sysview_desc.py deps/threadx/common/inc/tx_trace.h deps/threadx/common/inc/tx_api.h \
        txsv/SYSVIEW_ThreadX_native.txt txsv/txsv_thread_params.h

It also writes txsv_thread_params.h: which trace point parameters are thread
pointers, so the adapter sends them as SystemView task IDs and %t resolves
to the task name.

Re-run on every ThreadX update.
"""
import re, sys

OS_ID_BASE = 32                         # TXSV_OS_ID_BASE in txsv_adapter.c
MAX_ID = 511                            # SystemView description-file limit

TRACE_RE = re.compile(r"#define\s+TX_TRACE_(\w+)\s+(\d+)\s*/\*(.*?)\*/")
PARAM_RE = re.compile(r"I(\d)\s*=\s*(?:I\d\s*=\s*)?([^,]*?)\s*(?=,|I\d\s*=|$)")
STATE_RE = re.compile(r"#define\s+TX_(\w+)\s+\(\(UINT\)\s*(\d+)\)")
STATES = ["READY", "COMPLETED", "TERMINATED", "SUSPENDED", "SLEEP", "QUEUE_SUSP",
          "SEMAPHORE_SUSP", "EVENT_FLAG", "BLOCK_MEMORY", "BYTE_MEMORY", "IO_DRIVER",
          "FILE", "TCP_IP", "MUTEX_SUSP", "PRIORITY_CHANGE"]


def fmt(desc):
    d = desc.lower()
    if "wait option" in d:
        return "%WaitOption"
    if "thread ptr" in d or d in ("thread", "owning thread", "next thread", "current thread"):
        return "%t"
    if d in ("previous_state", "new_state", "thread state"):
        return "%ThreadState"
    if "ptr" in d or "flags" in d or "address" in d or "start" in d or d == "stack":
        return "%p"
    return "%u"


def label(desc):
    return re.sub(r"[\W_]+", "", desc.title()) or "Arg"


def main(trace_h, api_h, desc_out, header_out):
    states = {}
    for m in STATE_RE.finditer(open(api_h).read()):
        if m.group(1) in STATES:
            states[int(m.group(2))] = m.group(1).replace("_", " ").capitalize()
    state_list = ", ".join("%d=%s" % (k, v) for k, v in sorted(states.items()))
    # NamedType values are space-separated "value=Name" tokens: no spaces or commas
    state_named = " ".join("%d=%s" % (k, v.replace(" ", "_")) for k, v in sorted(states.items()))

    out = ["# Generated by tools/gen_sysview_desc.py from upstream ThreadX tx_trace.h.",
           "# Event ID = TX_TRACE_<X> + %d, parameters = trace point I1..I4." % OS_ID_BASE,
           "# Copy to SystemView's Description/ directory (or a project's .sysview/).",
           "",
           "Option    ReversePriority",
           "NamedType WaitOption  *=%u 0=TX_NO_WAIT 0xFFFFFFFF=TX_WAIT_FOREVER",
           "NamedType ThreadState *=%u " + state_named,
           "TaskState 0xFF " + state_list,
           "PreemptingTaskStates 0",
           ""]
    masks = []                           # (native id, name, thread-parameter bitmask)
    seen = set()
    for line in open(trace_h):
        m = TRACE_RE.search(line)
        if not m:
            continue
        name, num, comment = m.group(1), int(m.group(2)), m.group(3).strip()
        eid = num + OS_ID_BASE
        if eid > MAX_ID or eid in seen:
            continue                     # user events (4096..) map elsewhere
        seen.add(eid)
        params = []
        mask = 0
        if comment.lower() != "none":
            for pm in PARAM_RE.finditer(comment):
                desc = pm.group(2).strip()
                f = fmt(desc)
                if f == "%t":
                    mask |= 1 << (int(pm.group(1)) - 1)
                params.append("%s = %s" % (label(desc), f))
        out.append(("%-5d tx_%-44s %s" % (eid, name.lower(), ", ".join(params))).rstrip())
        if mask:
            masks.append((num, name, mask))
    with open(desc_out, "w") as f:
        f.write("\n".join(out) + "\n")

    max_id = max(n for n, _, _ in masks)
    h = ["/* Generated by tools/gen_sysview_desc.py from upstream ThreadX tx_trace.h. */",
         "/* Bit n set: trace point parameter I(n+1) is a TX_THREAD pointer, shown as  */",
         "/* %t in SYSVIEW_ThreadX_native.txt, so it must be sent as a SystemView ID.  */",
         "#define TXSV_THREAD_PARAM_MAX_ID  %du" % max_id,
         "static const unsigned char txsv_thread_params[TXSV_THREAD_PARAM_MAX_ID + 1u] = {"]
    h += ["    [%3d] = 0x%X,    /* TX_TRACE_%s */" % (n, mk, nm) for n, nm, mk in masks]
    h += ["};"]
    with open(header_out, "w") as f:
        f.write("\n".join(h) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
